/**
 * MVP-088: a server-side, anonymous display PROJECTION of a faithful original
 * supplier TEXT quote from MVP-063. This module never accesses contacts or
 * sends messages. The original signed/encrypted source stays private.
 *
 * Trusted broker must classify EVERY original line using reviewed evidence.
 * Identity-only lines can be omitted from display; no commercial line,
 * amount, condition or unknown may disappear. Any uncertain sensitive line
 * must fail closed, not be silently redacted or exposed.
 *
 * Output is NOT permission to disclose a real quote to a buyer: access, RLS,
 * source authenticity, trusted identity classification and temporal scope
 * must be independently verified by the calling private server.
 */
import {createHash} from 'node:crypto';
import type {EspejoPresupuestoMvp063} from './presupuesto-original-fiel-mvp063.ts';

const ID=/^anon_[a-z0-9_]{1,44}$/u;
const CONTACT=/(?:https?:\/\/|www\.|\b(?:tel(?:éfono)?|celular|whatsapp|cuit|cuil|correo|email|e-mail|direcci[oó]n\s+(?:del\s+)?(?:comercio|local)|raz[oó]n social)\b|[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}|(?:\+?\d[\s.-]?){9,})/iu;
const MONEY=/\$\s*\d|\b(?:ars|usd|u\$s)\s*\d/iu;
const KINDS=new Set(['solicitado','adicional','flete','descuento','condicion','total','sin_clasificar','identidad']);
export type ClaseLineaMvp088='solicitado'|'adicional'|'flete'|'descuento'|'condicion'|'total'|'sin_clasificar'|'identidad';
type Etiqueta=Readonly<{numeroLinea:number;clase:ClaseLineaMvp088}>;
export type EntradaPlantillaMvp088=Readonly<{
 fuente:EspejoPresupuestoMvp063;
 anonId:string;
 // MUST be generated by trusted server, not by browser or Whapi text.
 revisadoPorServidorConfiable:true;
 etiquetas:readonly Etiqueta[];
}>;
type LineaPublicable=Readonly<{numeroLinea:number;clase:Exclude<ClaseLineaMvp088,'identidad'>;textoExacto:string;importesLiterales:readonly string[]}>;
export type PlantillaAnonimaMvp088=Readonly<{
 tipo:'plantilla_cotironda_anonima_texto';
 proveedorAnonimo:string;
 renglones:readonly LineaPublicable[];
 totalDeclarado:Readonly<{importeLiteral:string;lineaFuente:number}>|null;
 estadoTotal:EspejoPresupuestoMvp063['estadoTotal'];
 sha256Fuente:string;
 renglonesFuente:number;
 renglonesIdentidadRetenidos:number;
 comparacionEconomica:'pendiente_conciliacion';
 contactosRevelados:false;
 archivoOriginalExpuesto:false;
}>;
const deny=():never=>{throw new Error('mvp088_presupuesto_no_publicable')};
const exact=(v:unknown,fields:readonly string[]):boolean=>v!==null&&
 typeof v==='object'&&!Array.isArray(v)&&Object.keys(v).length===fields.length&&
 Object.keys(v).every(k=>fields.includes(k));
export function construirPlantillaAnonimaMvp088(
 input:EntradaPlantillaMvp088
):PlantillaAnonimaMvp088{
 if(!exact(input,['fuente','anonId','revisadoPorServidorConfiable','etiquetas'])||
  input.revisadoPorServidorConfiable!==true||
  typeof input.anonId!=='string'||!ID.test(input.anonId)||
  !input.fuente||typeof input.fuente.textoOriginal!=='string'||
  typeof input.fuente.sha256!=='string'||
  !Array.isArray(input.fuente.renglones)||
  !Array.isArray(input.etiquetas)||
  input.fuente.renglones.length<1||input.fuente.renglones.length>350||
  input.etiquetas.length!==input.fuente.renglones.length)deny();
 const fuente=input.fuente;
 const calculated=createHash('sha256').update(fuente.textoOriginal,'utf8').digest('hex');
 if(calculated!==fuente.sha256||
  fuente.textoOriginal.split(/\r\n|\n|\r/u).length!==fuente.renglones.length)deny();
 const byNo=new Map<number,ClaseLineaMvp088>();
 for(const tag of input.etiquetas){
  if(!exact(tag,['numeroLinea','clase'])||
   !Number.isSafeInteger(tag.numeroLinea)||tag.numeroLinea<1||
   tag.numeroLinea>fuente.renglones.length||
   typeof tag.clase!=='string'||!KINDS.has(tag.clase)||
   byNo.has(tag.numeroLinea))deny();
  byNo.set(tag.numeroLinea,tag.clase);
 }
 const renglones:LineaPublicable[]=[];
 let retenidos=0;
 const originals=fuente.textoOriginal.split(/\r\n|\n|\r/u);
 for(let i=0;i<fuente.renglones.length;i++){
  const linea=fuente.renglones[i],literal=originals[i];
  const clase=byNo.get(i+1);
  if(linea.numero!==i+1||linea.textoExacto!==literal||
   !Array.isArray(linea.importesLiterales)||!clase)deny();
  // A header with a price is not identity-only: keeping that price is mandatory.
  if(clase==='identidad'){
   if(MONEY.test(literal)||linea.importesLiterales.length>0)deny();
   retenidos++;
   continue;
  }
  // A plausible contact in a displayed source line would deanonymize supplier.
  // Send to private review instead of deleting any part of their quoted price.
  if(CONTACT.test(literal))deny();
  // A server tag cannot suppress an explicit total: preserve it verbatim.
  renglones.push(Object.freeze({
   numeroLinea:i+1,clase,
   textoExacto:literal,
   importesLiterales:Object.freeze([...linea.importesLiterales])
  }));
 }
 if(renglones.length===0)deny();
 if(fuente.totalDeclarado){
  const no=fuente.totalDeclarado.numeroLinea;
  if(byNo.get(no)==='identidad'||
    fuente.renglones[no-1]?.textoExacto!==fuente.totalDeclarado.lineaExacta||
    !fuente.totalDeclarado.lineaExacta.includes(fuente.totalDeclarado.importeLiteral))deny();
 }
 return Object.freeze({
  tipo:'plantilla_cotironda_anonima_texto',
  proveedorAnonimo:input.anonId,
  renglones:Object.freeze(renglones),
  totalDeclarado:fuente.totalDeclarado?Object.freeze({
   importeLiteral:fuente.totalDeclarado.importeLiteral,
   lineaFuente:fuente.totalDeclarado.numeroLinea
  }):null,
  estadoTotal:fuente.estadoTotal,
  sha256Fuente:fuente.sha256,
  renglonesFuente:fuente.renglones.length,
  renglonesIdentidadRetenidos:retenidos,
  comparacionEconomica:'pendiente_conciliacion',
  contactosRevelados:false,
  archivoOriginalExpuesto:false
 });
}
